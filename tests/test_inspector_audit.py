# ── Inspector Tests ──────────────────────────────────────────

class TestResponseInspector:
    """Test placeholder verification and response scanning."""

    def test_valid_placeholders_are_safe(
        self, inspector: ResponseInspector, vault: PIIVault
    ):
        """Placeholders that exist in the vault should be marked valid and safe."""
        vault.store("s1", "PERSON", "PERSON_1", "Rahul Sharma")
        vault.store("s1", "EMAIL_ADDRESS", "EMAIL_ADDRESS_1", "rahul@test.com")

        report = inspector.inspect(
            "Hello PERSON_1, sent update to EMAIL_ADDRESS_1.",
            session_id="s1",
        )

        assert report.is_safe is True
        assert report.valid_placeholders == ["PERSON_1", "EMAIL_ADDRESS_1"]
        assert report.hallucinated_placeholders == []
        assert report.safe_placeholders_to_restore == ["PERSON_1", "EMAIL_ADDRESS_1"]

    def test_hallucinated_placeholder_flagged(
        self, inspector: ResponseInspector, vault: PIIVault
    ):
        """Placeholders generated by LLM that do NOT exist in the vault must be flagged."""
        vault.store("s1", "PERSON", "PERSON_1", "Rahul Sharma")

        # LLM invents PERSON_99
        report = inspector.inspect(
            "Hello PERSON_1 and PERSON_99!",
            session_id="s1",
        )

        assert report.is_safe is False
        assert "PERSON_99" in report.hallucinated_placeholders
        assert "PERSON_1" in report.valid_placeholders
        # Only valid placeholder should be restored
        assert report.safe_placeholders_to_restore == ["PERSON_1"]

    def test_corrupted_placeholder_flagged(
        self, inspector: ResponseInspector, vault: PIIVault
    ):
        """Corrupted patterns like PERSON_ (without index) should trigger warnings."""
        report = inspector.inspect(
            "Hello PERSON_ how are you?",
            session_id="s1",
        )

        assert report.is_safe is False
        assert len(report.corrupted_placeholders) > 0

    def test_empty_response(self, inspector: ResponseInspector):
        """Empty or blank response should be marked safe without errors."""
        report = inspector.inspect("", session_id="s1")
        assert report.is_safe is True
        assert report.placeholders_found == []

    def test_detects_new_pii_generated_by_llm(
        self, inspector: ResponseInspector, vault: PIIVault
    ):
        """If the LLM invents a new credit card or email, it should be detected."""
        report = inspector.inspect(
            "Your newly assigned card is 4111-1111-1111-1111.",
            session_id="s1",
        )

        assert "CREDIT_CARD" in report.new_pii_detected
        assert report.is_safe is False


# ── Audit Logger Tests ───────────────────────────────────────

class TestAuditLogger:
    """Test audit log writing, reading, and privacy constraints."""

    def test_log_event_writes_valid_json(self, audit_logger: AuditLogger):
        """Should record structured event with timestamp."""
        record = audit_logger.log_event(
            event_type="chat_turn",
            session_id="s123",
            data={
                "turn": 1,
                "entities_found": 2,
                "processing_time_ms": 42.5,
                "is_safe": True,
            },
        )

        assert record["event_type"] == "chat_turn"
        assert record["session_id"] == "s123"
        assert "timestamp" in record

        events = audit_logger.read_events("s123")
        assert len(events) == 1
        assert events[0]["turn"] == 1

    def test_forbidden_keys_rejected(self, audit_logger: AuditLogger):
        """Attempting to log raw prompts or PII must raise ValueError."""
        with pytest.raises(ValueError, match="Audit security violation"):
            audit_logger.log_event(
                event_type="chat_turn",
                session_id="s1",
                data={"prompt": "Secret prompt with PII"},
            )

        with pytest.raises(ValueError, match="Audit security violation"):
            audit_logger.log_event(
                event_type="chat_turn",
                session_id="s1",
                data={"original_value": "Rahul Sharma"},
            )

